import type { CallPolicy, SimConfig } from '../sim/types';

export interface PieceDef {
  id: string;
  name: string;
  icon: LucideIcon;
  blurb: string; // one line for the bin
  kind: 'station' | 'node' | 'wire' | 'saga';
  targets: string[]; // node ids, wire ids, or the station id it creates
  isOn: (c: SimConfig, target: string) => boolean;
  add: (c: SimConfig, target: string) => SimConfig;
  remove?: (c: SimConfig, target: string) => SimConfig;
  dials?: (target: string) => string[];
  label?: (c: SimConfig, target: string) => string; // sticker text
  inBin?: boolean;
  bad?: boolean; // an anti-pattern already on the map, to be removed
}

const POLICY_WIRES: Record<string, 'pay' | 'recs' | 'inv'> = { 'order-payment': 'pay', 'order-recs': 'recs', 'order-inventory': 'inv' };
const pol = (c: SimConfig, w: string) => c[POLICY_WIRES[w]] as CallPolicy;
const setPol = (c: SimConfig, w: string, p: Partial<CallPolicy>): SimConfig => {
  const k = POLICY_WIRES[w];
  return { ...c, [k]: { ...(c[k] as CallPolicy), ...p } };
};
const ms = (v: number) => (v >= 1000 ? `${+(v / 1000).toFixed(1)}s` : `${v}ms`);
const policyWires = Object.keys(POLICY_WIRES);
const ENTRY_WIRES = ['gateway-order', 'mobile-order', 'web-order'];
const FALLBACK_LABEL: Record<string, string> = {
  none: 'error page',
  message: 'clear message',
  omit: 'leave it out',
  stale: 'saved copy',
  pretend: 'pretend it worked',
};

