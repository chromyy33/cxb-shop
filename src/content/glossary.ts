// Glossary: plain-language terms, each with a small live map built from the same canvas pieces.
import type { DeepPartial } from '../sim/defaults';
import type { DepName, Env, Sim } from '../sim/engine';
import type { SimConfig } from '../sim/types';

export interface Term {
  id: string;
  term: string;
  short: string; // one plain sentence
  whatIf: string; // the question it answers
  more: string; // two or three more sentences
  nodes: string[];
  cfg?: DeepPartial<SimConfig>;
  env?: Partial<Env>;
  incident?: { at: number; until?: number; label: string; run: (s: Sim) => void; undo?: (s: Sim) => void };
  parts: string[]; // which parts to show on the map
  scenario?: string; // where to practise it
  group: 'Basics' | 'Front door' | 'Messages' | 'Failures' | 'Data';
}

